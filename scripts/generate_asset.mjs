import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";

function runBsk(args) {
  return execFileSync("bsk", args, { encoding: "utf-8", maxBuffer: 50 * 1024 * 1024 });
}

function sync() {
  const out = runBsk(["cooperate", "sync", "--session", "dhom", "--json"]);
  return JSON.parse(out);
}

function evaluate(code) {
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const syncData = sync();
      return runBsk(["evaluate", "--session", "dhom", "--context", syncData.context_id, code]);
    } catch (err) {
      if (attempt === 4) throw err;
      runBsk(["wait-ms", "1000"]);
    }
  }
}

async function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

export async function generateAsset(prompt, targetFile, aspectRatio = "1:1") {
  console.log(`\n========================================`);
  console.log(`Generating asset: ${targetFile}`);
  console.log(`Prompt: "${prompt}" (Ratio: ${aspectRatio})`);

  // 1. Get initial image URLs
  const initialImgsRaw = evaluate("(() => JSON.stringify(Array.from(document.querySelectorAll('img')).map(i => i.src)))()");
  const initialImgs = new Set(JSON.parse(initialImgsRaw));
  console.log(`Initial image count: ${initialImgs.size}`);

  // 2. Adjust aspect ratio if specified
  if (aspectRatio) {
    evaluate(`(async () => {
      const settingsBtn = document.querySelector('button.settings-trigger-button, button[aria-label="ทริกเกอร์การตั้งค่า"]');
      if (settingsBtn) {
        settingsBtn.click();
        await new Promise(r => setTimeout(r, 400));
        const labels = Array.from(document.querySelectorAll('label, .mat-button-toggle-button, [role="radio"]'));
        const targetBtn = labels.find(l => l.innerText.trim().includes('${aspectRatio}'));
        if (targetBtn) {
          targetBtn.click();
          await new Promise(r => setTimeout(r, 300));
        }
        settingsBtn.click();
        await new Promise(r => setTimeout(r, 400));
      }
    })()`);
    await sleep(600);
  }

  // 3. Clear and type prompt in ProseMirror
  evaluate(`(() => {
    const editor = document.querySelector('div.ProseMirror');
    if (!editor) return 'no editor';
    editor.focus();
    document.execCommand('selectAll', false, null);
    document.execCommand('delete', false, null);
    document.execCommand('insertText', false, ${JSON.stringify(prompt)});
    editor.dispatchEvent(new Event('input', { bubbles: true }));
    editor.dispatchEvent(new Event('change', { bubbles: true }));
    return 'typed';
  })()`);
  await sleep(800);

  // 4. Click Generate button using bsk click on the selector
  const syncAfterType = sync();
  try {
    const clickOut = runBsk([
      "click",
      "--selector",
      'button.generate-icon-button, button[aria-label="เริ่มสร้าง"]',
      "--session",
      "dhom",
      "--context",
      syncAfterType.context_id
    ]);
    console.log("Generate clicked via bsk:", clickOut.trim());
  } catch (err) {
    console.warn("bsk click warning, falling back to eval click:", err.message);
    evaluate(`(() => {
      const btn = document.querySelector('button.generate-icon-button, button[aria-label="เริ่มสร้าง"]');
      if (btn) btn.click();
    })()`);
  }

  // 5. Wait for new image to appear
  console.log("Waiting for new images to be generated by Google Flow...");
  let newImgUrl = null;
  const startTime = Date.now();
  for (let i = 0; i < 40; i++) {
    await sleep(2500);
    try {
      const currentImgsRaw = evaluate("(() => JSON.stringify(Array.from(document.querySelectorAll('img')).map(i => i.src)))()");
      const currentImgs = JSON.parse(currentImgsRaw);
      
      const newImages = currentImgs.filter(src => src.includes('/asb/') && !initialImgs.has(src));
      if (newImages.length > 0) {
        newImgUrl = newImages[0];
        const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
        console.log(`Success! Found ${newImages.length} new image(s) in ${elapsed}s!`);
        break;
      }
    } catch (e) {
      // transient sync/eval error, continue polling
    }
  }

  if (!newImgUrl) {
    throw new Error("Timeout waiting for new generated image");
  }

  // 6. Download image at high resolution (s1200) with retry
  const hiResUrl = newImgUrl.replace(/=s\d+-rw/, "=s1200");
  console.log(`Downloading high-res image: ${hiResUrl.substring(0, 70)}...`);

  await sleep(1500);

  let evalOut = null;
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const fetchCode = `(async () => {
        const res = await fetch(${JSON.stringify(hiResUrl)});
        const blob = await res.blob();
        return new Promise((resolve) => {
          const reader = new FileReader();
          reader.onloadend = () => resolve(reader.result);
          reader.readAsDataURL(blob);
        });
      })()`;
      evalOut = evaluate(fetchCode);
      if (evalOut && evalOut.includes("data:image/")) break;
    } catch (err) {
      console.log(`Download attempt ${attempt + 1} retrying...`);
      await sleep(1500);
    }
  }

  if (!evalOut) throw new Error("Failed to download image base64");

  const base64Data = evalOut.trim().replace(/^data:image\/\w+;base64,/, "");
  const buffer = Buffer.from(base64Data, "base64");

  fs.mkdirSync(path.dirname(targetFile), { recursive: true });
  fs.writeFileSync(targetFile, buffer);
  console.log(`Saved ${buffer.length} bytes to ${targetFile}`);
  return targetFile;
}

if (process.argv[1].endsWith("generate_asset.mjs") && process.argv[2]) {
  const [,, p, t, r] = process.argv;
  generateAsset(p, t, r || "1:1").catch(err => {
    console.error(err);
    process.exit(1);
  });
}
