import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";

const BSK = "C:\\Users\\USER\\.local\\bin\\bsk.exe";
const SESSION = "agal";
const TAB = "377021056";

function runBsk(args) {
  return execFileSync(BSK, args, { encoding: "utf-8", maxBuffer: 50 * 1024 * 1024 });
}

function sync() {
  const out = runBsk(["cooperate", "sync", "--session", SESSION, "--tab-id", TAB, "--json"]);
  return JSON.parse(out);
}

function evaluate(code) {
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const syncData = sync();
      return runBsk(["evaluate", "--session", SESSION, "--tab-id", TAB, "--context", syncData.context_id, code]);
    } catch (err) {
      if (attempt === 4) throw err;
      runBsk(["wait-ms", "1000"]);
    }
  }
}

async function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function generateAsset(prompt, targetFile) {
  console.log(`\n========================================`);
  console.log(`Generating asset: ${targetFile}`);
  console.log(`Prompt: "${prompt}"`);

  // 1. Get initial image URLs
  const initialImgsRaw = evaluate("(() => JSON.stringify(Array.from(document.querySelectorAll('img')).map(i => i.src)))()");
  const initialImgs = new Set(JSON.parse(initialImgsRaw));
  console.log(`Initial image count: ${initialImgs.size}`);

  // 2. Clear and type prompt in ProseMirror
  evaluate(`(() => {
    const editor = document.querySelector('div.ProseMirror');
    if (!editor) return 'no editor';
    editor.focus();
    document.execCommand('selectAll', false, null);
    document.execCommand('delete', false, null);
    document.execCommand('insertText', false, ${JSON.stringify(prompt)});
    editor.dispatchEvent(new Event('input', { bubbles: true }));
    editor.dispatchEvent(new Event('change', { bubbles: true }));
    return 'typed';
  })()`);
  await sleep(800);

  // 3. Click Generate button
  const syncAfterType = sync();
  try {
    const clickOut = runBsk([
      "click",
      "--selector",
      'button.generate-icon-button, button[aria-label="เริ่มสร้าง"]',
      "--session",
      SESSION,
      "--tab-id",
      TAB,
      "--context",
      syncAfterType.context_id
    ]);
    console.log("Generate clicked via bsk:", clickOut.trim());
  } catch (err) {
    console.warn("bsk click warning, falling back to eval click:", err.message);
    evaluate(`(() => {
      const btn = document.querySelector('button.generate-icon-button, button[aria-label="เริ่มสร้าง"]');
      if (btn) btn.click();
    })()`);
  }

  // 4. Wait for new image to appear
  console.log("Waiting for new images to be generated by Google Flow...");
  let newImgUrl = null;
  const startTime = Date.now();
  for (let i = 0; i < 40; i++) {
    await sleep(2500);
    const currentImgsRaw = evaluate("(() => JSON.stringify(Array.from(document.querySelectorAll('img')).map(i => i.src)))()");
    const currentImgs = JSON.parse(currentImgsRaw);
    for (const src of currentImgs) {
      if (src && src.includes("googleusercontent.com") && !initialImgs.has(src)) {
        newImgUrl = src;
        break;
      }
    }
    if (newImgUrl) break;
    process.stdout.write(`.`);
  }

  if (!newImgUrl) {
    throw new Error(`Timeout waiting for generated image for prompt: ${prompt}`);
  }

  console.log(`\nNew image detected: ${newImgUrl.slice(0, 80)}...`);

  // Upgrade image resolution
  let highResUrl = newImgUrl;
  if (highResUrl.includes("=")) {
    highResUrl = highResUrl.replace(/=s\d+.*$/, "=s1200");
  }

  // 5. Download image via Node fetch
  console.log(`Downloading high-res image from: ${highResUrl.slice(0, 80)}...`);
  const response = await fetch(highResUrl);
  if (!response.ok) throw new Error(`HTTP error ${response.status} fetching image`);
  const arrayBuffer = await response.arrayBuffer();
  const buffer = Buffer.from(arrayBuffer);

  const outDir = path.dirname(targetFile);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(targetFile, buffer);

  console.log(`Saved successfully to ${targetFile} (${(buffer.length / 1024).toFixed(1)} KB)`);
}

async function main() {
  // Asset 1: Frog peeking over card edge
  await generateAsset(
    "A cute chubby green clay frog with lotus leaf hat, peeking from behind an edge, holding on with two tiny hands over the top border, big friendly round black eyes, blush cheeks, pure white isolated background, 3D claymation miniature style, high detail",
    path.resolve("apps/web/public/images/mascots/frog-mascot-peeking.png")
  );

  await sleep(3000);

  // Asset 2: Pig resting chin over card edge
  await generateAsset(
    "A cute baby pink clay pig resting chin and front paws over a horizontal ledge, sleepy sweet happy smile, blushing cheeks, pure white isolated background, 3D claymation miniature style, high detail",
    path.resolve("apps/web/public/images/mascots/pig-mascot-peeking.png")
  );

  console.log("\nAll peeking mascots created successfully!");
}

main().catch((err) => {
  console.error("Error generating assets:", err);
  process.exit(1);
});
